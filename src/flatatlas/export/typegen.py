"""JSON Schemas and TypeScript types from the export models (PLAN §11.1, P1-09).

``schemas()`` gives one JSON Schema per file shape; ``typescript()`` turns the schemas of the
models into ``web/src/lib/data/types.ts``. The converter is small on purpose: it knows the
constructs ``export/models.py`` uses (objects, arrays, literals, nullable and optional fields,
``dict[str, X]``, ``$ref``) and raises on anything else, so a new construct is a visible change
instead of a wrong type. A test compares the committed files with a fresh run (the "in sync" check).
"""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from pathlib import Path
from typing import Any, get_args

from pydantic import BaseModel

from flatatlas.export import models
from flatatlas.settings import PROJECT_ROOT

WEB_DATA = PROJECT_ROOT / "web" / "src" / "lib" / "data"
SCHEMA_DIR = WEB_DATA / "schema"
TYPES_FILE = WEB_DATA / "types.ts"

HEADER = """\
// GENERATED by `uv run flatatlas export types` from src/flatatlas/export/models.py.
// Do not edit by hand: change the models and run the command again (a test checks they agree).
// Field names are snake_case on purpose: they are the column names of the exported release.
"""

IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


class TypeGenError(ValueError):
    """The schema uses something the converter does not know."""


def schema_of(model: type[BaseModel]) -> dict[str, Any]:
    return model.model_json_schema(by_alias=True, mode="serialization")


def schemas() -> dict[str, str]:
    """File name -> JSON text of the schema for every file shape."""
    out = {}
    for name, model in models.SCHEMA_MODELS.items():
        out[f"{name}.schema.json"] = json.dumps(schema_of(model), indent=2, sort_keys=True) + "\n"
    return out


# -- schema -> TypeScript -----------------------------------------------------------------------


def _ts(node: Mapping[str, Any]) -> str:
    if "$ref" in node:
        return str(node["$ref"]).rsplit("/", 1)[-1]
    if "const" in node:
        return _literal(node["const"])
    if "enum" in node:
        return " | ".join(_literal(v) for v in node["enum"])
    if "anyOf" in node:
        return " | ".join(_ts(n) for n in node["anyOf"])
    kind = node.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "items" not in node:
            raise TypeGenError(f"an array without a single item type: {dict(node)}")
        item = _ts(node["items"])
        return f"({item})[]" if " | " in item else f"{item}[]"
    if kind == "object" and isinstance(node.get("additionalProperties"), dict):
        return f"Record<string, {_ts(node['additionalProperties'])}>"
    raise TypeGenError(f"no TypeScript for {dict(node)}")


def _literal(value: Any) -> str:
    if isinstance(value, str):
        return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"
    raise TypeGenError(f"only string literals are supported, got {value!r}")


def _key(name: str) -> str:
    return name if IDENT.match(name) else _literal(name)


def _is_null(node: Mapping[str, Any]) -> bool:
    return node.get("type") == "null"


def _comment(text: str | None, indent: str) -> str:
    if not text:
        return ""
    return f"{indent}/** {' '.join(text.replace('``', '`').split())} */\n"


def interface(model: type[BaseModel]) -> str:
    schema = schema_of(model)
    required = set(schema.get("required", []))
    lines = [_comment(model.__doc__ and model.__doc__.strip().split("\n\n")[0], "")]
    lines.append(f"export interface {model.__name__} {{\n")
    for name, prop in schema["properties"].items():
        text = _comment(prop.get("description"), "\t")
        optional = name not in required
        node = dict(prop)
        if optional and "anyOf" in node:
            members = [m for m in node["anyOf"] if not _is_null(m)]
            node = members[0] if len(members) == 1 else {"anyOf": members}
        text += f"\t{_key(name)}{'?' if optional else ''}: {_ts(node)};\n"
        lines.append(text)
    lines.append("}\n")
    return "".join(lines)


def typescript() -> str:
    parts = [HEADER]
    for alias, literal in (
        ("EdgeType", models.EdgeType),
        ("LateralEdgeType", models.LateralEdgeType),
        ("TagStatus", models.TagStatus),
    ):
        parts.append(
            f"export type {alias} = {' | '.join(_literal(v) for v in get_args(literal))};\n"
        )
    for model in models.TYPE_MODELS:
        parts.append(interface(model))
    return "\n".join(parts)


# -- files --------------------------------------------------------------------------------------


def expected_files() -> dict[Path, str]:
    files = {SCHEMA_DIR / name: text for name, text in schemas().items()}
    files[TYPES_FILE] = typescript()
    return files


def write() -> list[Path]:
    SCHEMA_DIR.mkdir(parents=True, exist_ok=True)
    written = []
    for path, text in expected_files().items():
        path.write_text(text, encoding="utf-8")
        written.append(path)
    return written


def out_of_date() -> list[Path]:
    """Files that are missing or differ from a fresh generation."""
    return [
        path
        for path, text in expected_files().items()
        if not path.exists() or path.read_text(encoding="utf-8") != text
    ]
