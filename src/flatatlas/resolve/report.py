"""``reports/resolve-<profile>.md``: what the resolve stage decided, for a human to read (P1-04).

Sections: totals; source matching (accepted by method, rejected by reason); every version merge
and every uncertain, vetoed or blocked pair with its evidence; a hash-ordered sample of 30
cross-source joins; author mapping, with the cases where the evidence conflicts.
"""

from __future__ import annotations

import hashlib
import re
from collections import Counter
from typing import Any

from flatatlas.resolve.inputs import Inputs
from flatatlas.resolve.merge import PairScore
from flatatlas.resolve.works import Resolved

SAMPLE_SIZE = 30
SAMPLE_SEED = "p1-04"


def _cell(text: object) -> str:
    return str(text if text is not None else "").replace("|", "\\|").replace("\n", " ")


def _table(header: list[str], rows: list[list[object]]) -> list[str]:
    if not rows:
        return ["_none_", ""]
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return [*lines, ""]


def _hash_order(items: list[Any], key: Any) -> list[Any]:
    return sorted(
        items, key=lambda x: hashlib.sha256(f"{SAMPLE_SEED}|{key(x)}".encode()).hexdigest()
    )


def render(resolved: Resolved, inputs: Inputs, *, profile: str) -> str:
    papers = {p["dblp_key"]: p for p in inputs.papers}
    key_of_version = {v: k for k, v in resolved.version_of_key.items()}
    oa_work = {w["openalex_id"]: w for w in inputs.oa_works}
    s2_paper = {p["s2_corpus_id"]: p for p in inputs.s2_papers}
    author_name = {a["dblp_pid"]: a["display_name"] for a in resolved.authors}
    s = resolved.stats

    def label(key: str) -> str:
        p = papers[key]
        return f"{p['title']} ({key}, {p['edition_year']})"

    out = [f"# Resolve report — {profile}", ""]
    out += [
        "Generated by `flatatlas resolve`. Every number below comes from the run it describes;",
        "thresholds are in `config/resolve.yaml`.",
        "",
        "## Totals",
        "",
    ]
    out += _table(
        ["what", "count"],
        [
            ["papers (DBLP, front matter left out)", s["papers"]],
            ["works", s["works"]],
            ["versions", s["versions"]],
            ["versions merged into an earlier one", s["merged_versions"]],
            ["venues / editions", f"{s['venues']} / {s['editions']}"],
            ["authors (DBLP PIDs)", s["authors"]],
            ["authorships", s["authorships"]],
            ["institutions", s["institutions"]],
            ["citation edges inside the corpus", s["citation_edges"]],
            ["  in both OpenAlex and Semantic Scholar", s["citation_edges_in_both_sources"]],
            ["IDs minted in this run", s.get("ids_minted", "n/a")],
        ],
    )

    out += ["## Source matching (PLAN §8.1)", ""]
    by_method: Counter[tuple[str, str]] = Counter(
        (m["source"], m["method"]) for m in resolved.matches
    )
    out += _table(
        ["source", "method", "papers"],
        [[src, method, n] for (src, method), n in sorted(by_method.items())],
    )
    rejected = Counter(
        (r["source"], re.sub(r"[\d.]+", "N", r["reason"])) for r in resolved.rejected_matches
    )
    out += [
        f"Records returned by a lookup but **not** accepted as the same paper: "
        f"{len(resolved.rejected_matches)}.",
        "",
    ]
    out += _table(
        ["source", "reason", "papers"],
        [[src, reason, n] for (src, reason), n in sorted(rejected.items())],
    )

    merged = [p for p in resolved.pairs if p.verdict == "merge"]
    out += ["## Version merges (PLAN §8.2)", ""]
    out += [
        f"{len(resolved.pairs)} candidate pairs were scored: {s['pairs_merge']} merge, "
        f"{s['pairs_uncertain']} uncertain, {s['pairs_vetoed']} vetoed, "
        f"{s['merges_blocked']} blocked. All merges and every pair that was not ignored:",
        "",
    ]

    def pair_row(p: PairScore) -> list[object]:
        f = p.features
        return [
            label(p.earlier),
            label(p.later),
            f"{p.score:.3f}",
            p.verdict,
            f"t {f.get('title', 0):.2f} a {f.get('authors', 0):.2f} "
            f"e {f.get('embedding', 0):.2f} x {f.get('extra', 0):.2f}",
            "; ".join(p.reasons),
        ]

    header = [
        "earlier",
        "later",
        "score",
        "verdict",
        "title / authors / embedding / extra",
        "notes",
    ]
    for title, subset in (
        ("Merged", merged),
        ("Uncertain (not merged)", [p for p in resolved.pairs if p.verdict == "uncertain"]),
        ("Vetoed (similar but never merged)", [p for p in resolved.pairs if p.verdict == "vetoed"]),
        ("Merge refused: the group already holds that edition", resolved.blocked),
    ):
        out += [f"### {title}", ""]
        out += _table(header, [pair_row(p) for p in sorted(subset, key=lambda p: -p.score)])

    def join_rows(sample: list[dict[str, Any]]) -> list[list[object]]:
        rows = []
        for m in sorted(sample, key=lambda m: (m["source"], m["version_id"])):
            key = key_of_version[m["version_id"]]
            if m["source"] == "openalex":
                other = oa_work.get(m["external_id"], {})
                other_title, other_year = other.get("title"), other.get("publication_year")
            elif m["source"] == "s2":
                other = s2_paper.get(int(m["external_id"]), {})
                other_title, other_year = other.get("title"), other.get("year")
            else:
                other_title, other_year = None, None
            sim = m["title_similarity"]
            rows.append(
                [
                    label(key),
                    m["source"],
                    m["method"],
                    f"{m['confidence']:.2f}",
                    f"{other_title} ({other_year})" if other_title else m["external_id"],
                    f"{sim:.2f}" if sim is not None else "",
                ]
            )
        return rows

    join_header = ["paper", "source", "method", "confidence", "record", "title sim."]

    def order(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
        return _hash_order(items, lambda m: f"{m['version_id']}|{m['source']}")

    out += [f"## {SAMPLE_SIZE} random cross-source joins", ""]
    out += _table(join_header, join_rows(order(resolved.matches)[:SAMPLE_SIZE]))
    out += ["## 10 random joins by title only, per source (the weaker evidence)", ""]
    for source in ("openalex", "s2"):
        weak = [m for m in resolved.matches if m["source"] == source and m["method"] == "title"]
        out += [f"### {source}: {len(weak)} joins by title", ""]
        out += _table(join_header, join_rows(order(weak)[:10]))

    links = resolved.author_links
    conflicts = [k for k in links.values() if k.competing]
    out += ["## Authors (PLAN §8.3)", ""]
    out += [
        f"{s['authors']} authors, one per DBLP PID, none merged. OpenAlex author IDs: "
        f"{len(links)} linked to a PID, {len(resolved.unlinked_authors)} left unlinked.",
        "",
    ]
    by_reason = Counter(u.reason.split(" (")[0] for u in resolved.unlinked_authors)
    out += _table(
        ["unlinked because", "OpenAlex IDs"], [[r, n] for r, n in by_reason.most_common()]
    )
    out += ["### Linked, but other PIDs also had papers (conflicting evidence)", ""]
    out += _table(
        ["OpenAlex ID", "linked to", "papers agree / total", "method", "other PIDs"],
        [
            [
                k.external_id,
                f"{author_name.get(k.pid, k.pid)} ({k.pid})",
                f"{k.papers_agree} / {k.papers_total}",
                k.method,
                ", ".join(f"{author_name.get(pid, pid)} ({n})" for pid, n in k.competing.items()),
            ]
            for k in sorted(conflicts, key=lambda k: (k.share, k.external_id))
        ],
    )
    out += ["### Unlinked because the papers point to different PIDs", ""]
    out += _table(
        ["OpenAlex ID", "papers", "PIDs"],
        [
            [
                u.external_id,
                u.papers_total,
                ", ".join(f"{author_name.get(pid, pid)} ({n})" for pid, n in u.pids.items()),
            ]
            for u in resolved.unlinked_authors
            if len(u.pids) > 1
        ],
    )
    return "\n".join(out) + "\n"
