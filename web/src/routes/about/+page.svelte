<h1>About</h1>
<p>
	The FLAT Atlas is an open map of formal languages and automata theory, from the 1950s to today. It
	links topics, papers, authors and venues.
</p>
<p>
	It stores metadata and links only, never full texts. Every automatic assignment carries a
	confidence and a provenance. The pipeline and this site are open source:
	<a href="https://github.com/gmcmduarte/flat-atlas">github.com/gmcmduarte/flat-atlas</a>.
</p>
<p class="muted">
	The site is under construction. The data you see now is a small hand-written fixture, not the real
	corpus.
</p>
